import { useEffect, useState } from 'react';
import type { GameDetail } from '@dungeonmind/shared';
import { api } from '../api';
import { Markdown } from '../components/Markdown';
import { Modal } from '../components/Modal';
import { getSocket } from '../socket';

/** campaign.md: everyone reads it, the host edits it; every version is kept. */
export function CampaignModal({ g, onClose }: { g: GameDetail; onClose: () => void }) {
  const [data, setData] = useState<{ md: string; versions: { id: number; author: string; turn: number; at: string }[] }>();
  const [version, setVersion] = useState('');
  const [edit, setEdit] = useState<string>();
  const load = () => api(`/api/games/${g.id}/campaign${version ? `?version=${version}` : ''}`).then(setData);
  useEffect(() => {
    load();
    const s = getSocket();
    const on = (m: { gameId: string }) => m.gameId === g.id && !version && load();
    s.on('game:campaign', on);
    return () => void s.off('game:campaign', on);
  }, [version]);
  return (
    <Modal title="Campaign file" onClose={onClose} wide>
      {data && (
        <div className="space-y-3">
          <div className="flex flex-wrap items-center gap-2">
            <select className="input w-auto py-1 text-xs" value={version} onChange={(e) => setVersion(e.target.value)}>
              <option value="">Current</option>
              {data.versions.map((v) => (
                <option key={v.id} value={v.id}>
                  #{v.id} · turn {v.turn} · {v.author} · {v.at}
                </option>
              ))}
            </select>
            <a className="btn-ghost text-xs" href={`/api/games/${g.id}/export.md`}>
              Download save (.md)
            </a>
            {g.myRole === 'host' && !version && edit === undefined && (
              <button className="btn-ghost text-xs" onClick={() => setEdit(data.md)}>
                Edit
              </button>
            )}
          </div>
          {edit !== undefined ? (
            <>
              <textarea className="input h-[60vh] font-mono text-xs" value={edit} onChange={(e) => setEdit(e.target.value)} />
              <div className="flex gap-2">
                <button
                  className="btn"
                  onClick={async () => {
                    await api(`/api/games/${g.id}/campaign`, { method: 'PUT', body: { md: edit } });
                    setEdit(undefined);
                    load();
                  }}
                >
                  Save
                </button>
                <button className="btn-ghost" onClick={() => setEdit(undefined)}>
                  Cancel
                </button>
                <span className="text-xs text-slate-500">The party table is generated by the server and can't be edited.</span>
              </div>
            </>
          ) : (
            <Markdown text={data.md} className="readable text-sm" />
          )}
        </div>
      )}
    </Modal>
  );
}
